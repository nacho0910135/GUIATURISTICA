assert.match(authConfig, /secure_password_change = true/);
assert.match(provider, /\['auth\/callback', 'reset-password'\]\.includes\(nativePath\)/);
assert.match(provider, /exchangeCodeForSession\(code, flowId \? \{ flowId \} : undefined\)/);
