import { writeFile } from 'node:fs/promises';

const BASE_URL = 'https://www.visitcostarica.com';
const OUTPUT = new URL('../supabase/migrations/20260829020000_sync_complete_ict_commerce.sql', import.meta.url);
const SOURCE_URL = `${BASE_URL}/planning-your-trip`;

const sql = (value) => value == null ? 'null' : `'${String(value).replaceAll("'", "''")}'`;
const first = (value) => Array.isArray(value) ? value[0] : value;

function classify(source) {
  const businessType = Number(first(source.business_type));
  const activity = Number(first(source.activities));
  const title = String(first(source.title) ?? '').toLowerCase();

  if (businessType === 34) return ['food', 'restaurant'];
  if (businessType === 35) return ['guides_experiences', 'tour_operator'];
  if (businessType === 37 || businessType === 41) return ['lodging', 'hotel'];
  if (businessType === 38) return ['transport', 'airline'];
  if (businessType === 39) return ['rentals_equipment', 'rent_a_car'];
  if (activity === 51) return ['water_activities', 'boat_tours'];
  if (activity === 52) return ['transport', 'tourist_transport'];
  if (activity === 50) return ['adventure', 'aerial_tours'];
  if (activity === 54) return ['adventure', 'recreative_activities'];
  if (activity === 55) return ['nature', 'thematic_activities'];
  if (activity === 53) return ['guides_experiences', 'meetings_incentives'];
  if (/spa|wellness|thermal|termal|hot spring|yoga|massage|masaje/.test(title)) return ['wellness', 'wellness'];
  if (/artisan|artesan|souvenir|market|mercado|shop|tienda/.test(title)) return ['shopping', 'shopping'];
  if (/reserve|reserva|refugio|sanctuary|santuario|garden|jardín|jardin|wildlife|zoo|nature|natural/.test(title)) return ['nature', 'nature'];
  return ['adventure', 'tour'];
}

function point(source) {
  const match = String(first(source.field_map_points) ?? '').match(/^POINT \((-?\d+(?:\.\d+)?) (-?\d+(?:\.\d+)?)\)$/);
  return match ? [Number(match[1]), Number(match[2])] : [null, null];
}

async function fetchDirectory() {
  const tokenResponse = await fetch(`${BASE_URL}/session/token`);
  if (!tokenResponse.ok) throw new Error(`ICT token request failed: ${tokenResponse.status}`);
  const token = await tokenResponse.text();
  const response = await fetch(`${BASE_URL}/api/elastic-search`, {
    method: 'POST',
    headers: { Accept: 'application/json', 'Content-Type': 'application/json', 'X-CSRF-Token': token },
    body: JSON.stringify({
      url: 'business_listing',
      json_body: {
        from: 0,
        size: 10000,
        query: { bool: { must: [{ term: { status: true } }, { term: { field_checkbox: false } }] } },
        sort: [{ nid: { order: 'asc' } }],
      },
    }),
  });
  if (!response.ok) throw new Error(`ICT directory request failed: ${response.status}`);
  const payload = await response.json();
  const total = payload.hits?.total?.value;
  const hits = payload.hits?.hits ?? [];
  if (hits.length !== total) throw new Error(`Incomplete ICT response: received ${hits.length} of ${total}`);
  return hits.map((hit) => hit._source);
}

const records = await fetchDirectory();
const rows = records.map((source) => {
  const [category, subcategory] = classify(source);
  const [longitude, latitude] = point(source);
  const sourceId = String(first(source.nid));
  const title = String(first(source.title) ?? '').trim();
  const path = String(first(source.url) ?? '').trim();
  const image = String(first(source.thumbnail_image) ?? '').replace('http://test-visit-costa-rica.pantheonsite.io', BASE_URL) || null;
  return `  (${sql(sourceId)}, ${sql(category)}, ${sql(subcategory)}, ${sql(title)}, ${sql(path ? new URL(path, BASE_URL) : SOURCE_URL)}, ${sql(image)}, ${longitude ?? 'null'}, ${latitude ?? 'null'})`;
});

const generatedAt = new Date().toISOString();
const output = `-- Generated by scripts/sync-official-commerce.mjs from the complete active ICT directory.
-- Source: ${SOURCE_URL}; ${records.length} active records fetched ${generatedAt}.
-- Emergency records are intentionally outside the scope of this synchronization.
alter table public.commercial_services
  add column if not exists source_record_id text,
  alter column location drop not null;

create unique index if not exists commercial_services_ict_source_record_uidx
  on public.commercial_services (source_record_id)
  where source = 'ICT' and source_record_id is not null;

create temp table ict_commerce_import (
  source_record_id text primary key,
  category text not null,
  subcategory text not null,
  title text not null,
  external_url text,
  cover_image_url text,
  longitude double precision,
  latitude double precision
) on commit drop;

insert into ict_commerce_import values
${rows.join(',\n')};

insert into public.commercial_services (
  source_record_id, category, subcategories, main_category, subcategory, title,
  description, external_url, cover_image_url, location, source, data_source,
  source_license, source_updated_at, imported_at, certifications
)
select
  source_record_id, category, array[subcategory], category, subcategory, title,
  'Registro activo del directorio turístico oficial del ICT.', external_url, cover_image_url,
  case when longitude is not null and latitude is not null
    then st_setsrid(st_makepoint(longitude, latitude), 4326)
  end,
  'ICT', 'ICT · Visit Costa Rica', 'Fuente oficial del Instituto Costarricense de Turismo',
  ${sql(generatedAt)}::timestamptz, now(), array['Directorio oficial ICT']
from ict_commerce_import
on conflict (source_record_id) where source = 'ICT' and source_record_id is not null
do update set
  category = excluded.category,
  subcategories = excluded.subcategories,
  main_category = excluded.main_category,
  subcategory = excluded.subcategory,
  title = excluded.title,
  description = excluded.description,
  external_url = excluded.external_url,
  cover_image_url = excluded.cover_image_url,
  location = excluded.location,
  data_source = excluded.data_source,
  source_license = excluded.source_license,
  source_updated_at = excluded.source_updated_at,
  imported_at = excluded.imported_at,
  certifications = excluded.certifications;

delete from public.commercial_services service
where service.source = 'ICT'
  and service.source_record_id is not null
  and service.category <> 'emergency'
  and not exists (
    select 1 from ict_commerce_import incoming
    where incoming.source_record_id = service.source_record_id
  );
`;

await writeFile(OUTPUT, output, 'utf8');

const counts = records.reduce((result, source) => {
  const [category] = classify(source);
  result[category] = (result[category] ?? 0) + 1;
  return result;
}, {});
console.log(JSON.stringify({ total: records.length, categories: counts, output: OUTPUT.pathname }, null, 2));
